// Privacy-preserving password breach check helpers (k-anonymity model).
//
// Flow:
//   1. Browser computes SHA-1(password) locally.
//   2. Browser sends ONLY the first 5 hex chars (the "prefix") to our backend,
//      which proxies it to the HIBP Pwned Passwords range API.
//   3. API returns every hash SUFFIX sharing that prefix, with counts.
//   4. Browser compares the remaining 35 chars locally.
//   5. Password + full hash are discarded immediately.
//
// The plaintext password and full hash never leave the browser.

import type { PasswordCheckResult } from './types.js';

export type ExposureBand = PasswordCheckResult['exposureBand'];

export function bandForOccurrences(count: number): ExposureBand {
  if (count <= 0) return 'none';
  if (count < 10) return 'low';
  if (count < 100) return 'medium';
  if (count < 100_000) return 'high';
  return 'very_high';
}

/**
 * Parse a HIBP range response body and return the occurrence count for the
 * given 35-char uppercase hash suffix. Returns 0 when not present.
 * Tolerates blank lines, CRLF, and malformed rows.
 */
export function parseRangeResponse(body: string, suffix: string): number {
  const target = suffix.trim().toUpperCase();
  for (const rawLine of body.split('\n')) {
    const line = rawLine.trim();
    if (!line) continue;
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    const hashSuffix = line.slice(0, idx).toUpperCase();
    if (hashSuffix !== target) continue;
    const count = Number.parseInt(line.slice(idx + 1).trim(), 10);
    return Number.isFinite(count) && count > 0 ? count : 1;
  }
  return 0;
}

export function buildPasswordResult(occurrences: number): PasswordCheckResult {
  const band = bandForOccurrences(occurrences);
  const compromised = occurrences > 0;
  return {
    compromised,
    exposureBand: band,
    occurrences: compromised ? occurrences : 0,
    checkedAt: new Date().toISOString(),
    method: 'HIBP Pwned Passwords k-anonymity range query (SHA-1 prefix only)',
    note: compromised
      ? 'This password has appeared in known breach datasets. Appearing in a breach dataset does not necessarily mean one of your specific accounts was compromised — but the password should be considered public and must not be used anywhere.'
      : 'This password was not found in the queried Pwned Passwords dataset. That is not a guarantee it is safe or strong — breach datasets are incomplete.',
    recommendedActions: compromised
      ? [
          'Change this password anywhere it is currently used',
          'Never reuse it again on any account',
          'Choose a long, unique password (ideally generated by a password manager)',
          'Enable multi-factor authentication on important accounts',
          'Review active sessions and recovery methods on affected accounts',
        ]
      : [
          'Still prefer a long, unique password per account',
          'Use a password manager to avoid reuse',
          'Enable multi-factor authentication where possible',
        ],
  };
}

export function isValidHashPrefix(prefix: string): boolean {
  return /^[0-9A-Fa-f]{5}$/.test(prefix);
}
